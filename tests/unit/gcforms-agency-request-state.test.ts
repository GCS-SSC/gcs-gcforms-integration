// @vitest-environment jsdom
import { afterEach, describe, expect, it, vi } from 'vitest'
import { flushPromises, mount } from '@vue/test-utils'
import { defineComponent, h, ref } from 'vue'
import { translateGcsExtensionMessage, type GcsExtensionMessages } from '@gcs-ssc/extensions'
const locale = ref('en')
const api = vi.hoisted(() => ({ get: vi.fn(), post: vi.fn(), patch: vi.fn(), delete: vi.fn() }))
vi.mock('@gcs-ssc/extensions/ui', () => {
  const field = defineComponent({ setup: (_, { slots }) => () => h('label', slots.default?.()) })
  const input = defineComponent({
    props: ['modelValue'], emits: ['update:modelValue'],
    setup: (props, { emit }) => () => h('input', { value: props.modelValue, onInput: (event: Event) => emit('update:modelValue', (event.target as HTMLInputElement).value) })
  })
  const button = defineComponent({ name: 'TestButton', props: ['label', 'disabled'], emits: ['click'], setup: (props, { emit }) => () => h('button', { disabled: props.disabled, onClick: () => emit('click') }, props.label) })
  return {
    useExtensionI18n: (messages: GcsExtensionMessages) => ({ locale, t: (key: string) => translateGcsExtensionMessage(messages, locale.value, key) }),
    useExtensionApi: () => api,
    ExtensionButton: button, ExtensionSaveButton: button, ExtensionFormField: field,
    ExtensionInput: input, ExtensionRawTextarea: input, ExtensionCheckbox: input, ExtensionStatusSelect: input
  }
})
import AgencyConfig from '../../components/AgencyGcFormsIntegrationConfig.vue'
const deferred = <T,>() => {
  let resolve!: (value: T) => void
  let reject!: (reason: unknown) => void
  const promise = new Promise<T>((accept, fail) => {
    resolve = accept
    reject = fail
  })
  return { promise, resolve, reject }
}
const props = { modelValue: {}, agencyId: 'first', extension: { key: 'gcs-gcforms-integration' } as never }
const summary = (id: string) => ({ id, name_en: id, name_fr: id, formId: id, keyId: id, userId: id })
afterEach(() => { vi.resetAllMocks(); locale.value = 'en' })
describe('GC Forms Agency credential request state', () => {
  it.each(['create', 'edit'])('shows a failed %s for the current edited draft and retries its latest fields', async mode => {
    api.get.mockResolvedValue({ items: [summary('42')] })
    const save = deferred<{ item: ReturnType<typeof summary> }>()
    const write = mode === 'create' ? api.post : api.patch
    write.mockReturnValueOnce(save.promise).mockResolvedValueOnce({ item: summary('42') })
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    if (mode === 'create') await button('New credential').trigger('click')
    else await wrapper.get('[aria-label="Edit"]').trigger('click')
    expect(field('Private key').element.value).toBe('')
    await field('English name').setValue('Submitted')
    await field('Private key').setValue('submitted secret')
    await button('Save credential').trigger('click')
    expect(button('Save credential').element.disabled).toBe(true)
    await field('English name').setValue('Later name')
    await field('Private key').setValue('later secret')
    save.reject(new Error('server unavailable'))
    await flushPromises()
    expect(wrapper.get('[role="status"]').text()).toBe('Credential action failed.')
    expect(field('English name').element.value).toBe('Later name')
    expect(field('Private key').element.value).toBe('later secret')
    expect(write.mock.calls[0]?.[1]).toMatchObject({ name_en: 'Submitted', key: 'submitted secret' })
    expect(button('Save credential').element.disabled).toBe(false)
    expect(api.get).toHaveBeenCalledTimes(1)
    await button('Save credential').trigger('click')
    await flushPromises()
    expect(write).toHaveBeenCalledTimes(2)
    expect(write.mock.calls[1]?.[1]).toMatchObject({ name_en: 'Later name', key: 'later secret' })
    expect(wrapper.get('[role="status"]').text()).toBe('Credential saved.')
    expect(wrapper.findAll('label').some(item => item.attributes('label') === 'Private key')).toBe(false)
    wrapper.unmount()
  })

  it.each(['create', 'edit'])('shows a failed %s without later edits and retains the submitted secret', async mode => {
    api.get.mockResolvedValue({ items: [summary('42')] })
    const write = mode === 'create' ? api.post : api.patch
    write.mockRejectedValueOnce(new Error('server unavailable'))
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    if (mode === 'create') await wrapper.findAll('button').find(item => item.text() === 'New credential')!.trigger('click')
    else await wrapper.get('[aria-label="Edit"]').trigger('click')
    const secret = () => wrapper.findAll('label').find(item => item.attributes('label') === 'Private key')!.get('input')
    await secret().setValue('retry secret')
    await wrapper.findAll('button').find(item => item.text() === 'Save credential')!.trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="status"]').text()).toBe('Credential action failed.')
    expect(secret().element.value).toBe('retry secret')
    wrapper.unmount()
  })

  it('suppresses a rejected save for a replacement editor', async () => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValueOnce(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    await button('New credential').trigger('click')
    await button('Save credential').trigger('click')
    await button('New credential').trigger('click')
    await field('English name').setValue('Replacement')
    await field('Private key').setValue('replacement secret')
    save.reject(new Error('old write failed'))
    await flushPromises()
    expect(wrapper.find('[role="status"]').exists()).toBe(false)
    expect(field('English name').element.value).toBe('Replacement')
    expect(field('Private key').element.value).toBe('replacement secret')
    expect(button('Save credential').element.disabled).toBe(false)
    wrapper.unmount()
  })

  it.each(['agencyId', 'readOnly', 'disabled', 'enabled'])('suppresses rejected save feedback after %s departs and returns', async context => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValueOnce(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    await button('New credential').trigger('click')
    await button('Save credential').trigger('click')
    await wrapper.setProps({ [context]: context === 'agencyId' ? 'second' : context !== 'enabled' })
    await wrapper.setProps({ [context]: context === 'agencyId' ? 'first' : context === 'enabled' })
    await flushPromises()
    await button('New credential').trigger('click')
    const secret = () => wrapper.findAll('label').find(item => item.attributes('label') === 'Private key')!.get('input')
    await secret().setValue('replacement secret')
    save.reject(new Error('departed write failed'))
    await flushPromises()
    expect(api.post.mock.calls[0]?.[2].signal.aborted).toBe(true)
    expect(wrapper.find('[role="status"]').exists()).toBe(false)
    expect(secret().element.value).toBe('replacement secret')
    expect(button('Save credential').element.disabled).toBe(false)
    wrapper.unmount()
  })

  it('aborts a departed component save and consumes its late rejection', async () => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValueOnce(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    await wrapper.findAll('button').find(item => item.text() === 'New credential')!.trigger('click')
    await wrapper.findAll('button').find(item => item.text() === 'Save credential')!.trigger('click')
    wrapper.unmount()
    save.reject(new Error('departed write failed'))
    await flushPromises()
    expect(api.post.mock.calls[0]?.[2].signal.aborted).toBe(true)
    expect(api.get).toHaveBeenCalledTimes(1)
  })

  it('loads reactive Agency endpoint and rejects superseded summary', async () => {
    const old = deferred<{ items: ReturnType<typeof summary>[] }>()
    api.get.mockImplementation((endpoint: string) => endpoint.includes('/first/') ? old.promise : Promise.resolve({ items: [summary('new agency')] }))
    const wrapper = mount(AgencyConfig, { props })
    await wrapper.setProps({ agencyId: 'second' })
    await flushPromises()
    expect(wrapper.text()).toContain('new agency')
    old.resolve({ items: [summary('old agency')] })
    await flushPromises()
    expect(wrapper.text()).not.toContain('old agency')
    expect(api.get.mock.calls[0]?.[1].signal.aborted).toBe(true)
    wrapper.unmount()
  })
  it('keeps replacement credential draft when earlier save settles', async () => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValue(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    await button('New credential').trigger('click')
    await field('English name').setValue('First')
    await field('Private key').setValue('secret')
    await button('Save credential').trigger('click')
    expect(api.post).toHaveBeenCalledTimes(1)
    await button('New credential').trigger('click')
    await field('English name').setValue('Replacement')
    save.resolve({ ok: true, item: summary('42') })
    await flushPromises()
    expect(field('English name').element.value).toBe('Replacement')
    expect(field('Private key').element.value).toBe('')
    api.post.mockResolvedValue({ ok: true, item: summary('43') })
    await button('Save credential').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledTimes(2)
    expect(api.patch).not.toHaveBeenCalled()
    wrapper.unmount()
  })
  it('keeps edits made inside the same credential draft during save', async () => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValue(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    await button('New credential').trigger('click')
    await field('Private key').setValue('submitted')
    await button('Save credential').trigger('click')
    await field('Private key').setValue('new secret draft')
    save.resolve({ ok: true, item: summary('42') })
    await flushPromises()
    expect(field('Private key').element.value).toBe('new secret draft')
    expect(api.post.mock.calls[0]?.[1].key).toBe('submitted')
    api.patch.mockResolvedValue({ ok: true, item: summary('42') })
    await button('Save credential').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledTimes(1)
    expect(api.patch).toHaveBeenCalledWith('/agencies/first/credentials/42', expect.objectContaining({ key: 'new secret draft' }), expect.anything())
    wrapper.unmount()
  })
  it('ignores previous Agency save settlement after context replacement', async () => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValue(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    await button('New credential').trigger('click')
    await button('Save credential').trigger('click')
    await wrapper.setProps({ agencyId: 'second' })
    await flushPromises()
    await button('New credential').trigger('click')
    save.resolve({ ok: true, item: summary('42') })
    await flushPromises()
    expect(wrapper.findAll('label').find(item => item.attributes('label') === 'Private key')).toBeDefined()
    expect(api.get).toHaveBeenCalledTimes(2)
    expect(api.post.mock.calls[0]?.[2].signal.aborted).toBe(true)
    wrapper.unmount()
  })
  it.each(['saved secret', ''])('adopts created identity while preserving metadata and keeping blank edit-secret semantics (%s)', async keyDraft => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<unknown>()
    api.post.mockReturnValue(save.promise)
    api.patch.mockResolvedValue({ ok: true, item: summary('42') })
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    await button('New credential').trigger('click')
    await field('English name').setValue('Submitted name')
    await field('Private key').setValue('saved secret')
    await button('Save credential').trigger('click')
    await field('English name').setValue('Newer name')
    await field('Private key').setValue(keyDraft)
    save.resolve({ ok: true, item: summary('42') })
    await flushPromises()
    expect(field('English name').element.value).toBe('Newer name')
    expect(field('Private key').element.value).toBe('')
    expect(wrapper.findAll('label').find(item => item.attributes('label') === 'Private key')!.attributes('required')).toBe('false')
    await button('Save credential').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledTimes(1)
    expect(api.patch).toHaveBeenCalledWith('/agencies/first/credentials/42', expect.objectContaining({ name_en: 'Newer name' }), expect.anything())
    expect(api.patch.mock.calls[0]?.[1]).not.toHaveProperty('key')
    wrapper.unmount()
  })
  it.each(['readOnly', 'disabled'] as const)('keeps credential metadata readable and blocks Viewer mutations through %s', async capability => {
    api.get.mockResolvedValue({ items: [summary('Existing credential')] })
    const wrapper = mount(AgencyConfig, { props: { ...props, [capability]: true } })
    await flushPromises()
    expect(wrapper.text()).toContain('Existing credential')
    expect(wrapper.findAll('input').every(input => input.element.disabled)).toBe(true)
    expect(wrapper.findAll('button')).toHaveLength(0)
    expect(api.post).not.toHaveBeenCalled()
    expect(api.patch).not.toHaveBeenCalled()
    expect(api.delete).not.toHaveBeenCalled()
    await wrapper.setProps({ [capability]: false })
    await wrapper.findAll('button').find(button => button.text() === 'New credential')!.trigger('click')
    expect(wrapper.findAll('label').some(field => field.attributes('label') === 'Private key')).toBe(true)
    wrapper.unmount()
  })

  it('requires enabled credential operations while retaining editable configuration', async () => {
    api.get.mockResolvedValue({ items: [summary('Existing credential')] })
    const wrapper = mount(AgencyConfig, { props: { ...props, enabled: false } })
    await flushPromises()
    expect(wrapper.findAll('input').every(input => !input.element.disabled)).toBe(true)
    expect(wrapper.findAll('button').every(button => button.element.disabled)).toBe(true)
    for (const button of wrapper.findAllComponents({ name: 'TestButton' })) button.vm.$emit('click')
    await flushPromises()
    expect(api.post).not.toHaveBeenCalled()
    expect(api.patch).not.toHaveBeenCalled()
    expect(api.delete).not.toHaveBeenCalled()
    await wrapper.setProps({ enabled: true })
    await wrapper.findAll('button').find(button => button.text() === 'New credential')!.trigger('click')
    expect(wrapper.findAll('label').some(field => field.attributes('label') === 'Private key')).toBe(true)
    wrapper.unmount()
  })

  it.each(['readOnly', 'disabled', 'enabled'] as const)('rejects an earlier credential create after %s changes and allows a replacement session', async capability => {
    api.get.mockResolvedValue({ items: [] })
    const save = deferred<{ item: ReturnType<typeof summary> }>()
    api.post.mockReturnValueOnce(save.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const button = (label: string) => wrapper.findAll('button').find(item => item.text() === label)!
    const field = (label: string) => wrapper.findAll('label').find(item => item.attributes('label') === label)!.get('input')
    await button('New credential').trigger('click')
    await field('English name').setValue('Submitted')
    await field('Private key').setValue('submitted secret')
    await button('Save credential').trigger('click')
    await wrapper.setProps({ [capability]: capability === 'enabled' ? false : true })
    expect(api.post.mock.calls[0]?.[2].signal.aborted).toBe(true)
    expect(wrapper.findAll('label').some(item => item.attributes('label') === 'Private key')).toBe(false)
    await wrapper.setProps({ [capability]: capability !== 'enabled' ? false : true })
    await button('New credential').trigger('click')
    await field('English name').setValue('Replacement')
    save.resolve({ item: summary('42') })
    await flushPromises()
    expect(field('English name').element.value).toBe('Replacement')
    expect(field('Private key').element.value).toBe('')
    expect(api.get).toHaveBeenCalledTimes(1)
    api.post.mockResolvedValue({ item: summary('43') })
    await button('Save credential').trigger('click')
    await flushPromises()
    expect(api.post).toHaveBeenCalledTimes(2)
    expect(api.patch).not.toHaveBeenCalled()
    wrapper.unmount()
  })

  it('rejects delayed delete feedback and retained control events after access is revoked', async () => {
    api.get.mockResolvedValue({ items: [summary('Existing credential')] })
    const deletion = deferred<void>()
    api.delete.mockReturnValueOnce(deletion.promise)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    const edit = wrapper.findAllComponents({ name: 'TestButton' }).find(component => component.attributes('aria-label') === 'Edit')!
    await wrapper.get('[aria-label="Remove"]').trigger('click')
    expect(api.delete).toHaveBeenCalledTimes(1)
    await wrapper.setProps({ readOnly: true })
    edit.vm.$emit('click')
    await flushPromises()
    expect(wrapper.findAll('label').some(field => field.attributes('label') === 'Private key')).toBe(false)
    expect(wrapper.text()).toContain('Existing credential')
    await wrapper.setProps({ readOnly: false })
    deletion.resolve()
    await flushPromises()
    expect(api.get).toHaveBeenCalledTimes(1)
    expect(wrapper.text()).not.toContain('Credential deleted')
    await wrapper.get('[aria-label="Edit"]').trigger('click')
    expect(wrapper.findAll('label').some(field => field.attributes('label') === 'Private key')).toBe(true)
    wrapper.unmount()
  })

  it('distinguishes a credential read failure from true empty evidence and retries without losing a draft', async () => {
    api.get.mockRejectedValueOnce(new Error('network unavailable'))
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    expect(wrapper.text()).not.toContain('No credentials have been saved yet.')
    expect(wrapper.get('[role="alert"]').text()).toContain('Credentials could not be loaded.')
    locale.value = 'fr'
    await flushPromises()
    expect(wrapper.get('[role="alert"]').text()).toContain('Impossible de charger les identifiants')
    locale.value = 'en'
    await flushPromises()
    await wrapper.findAll('button').find(button => button.text() === 'New credential')!.trigger('click')
    const name = () => wrapper.findAll('label').find(item => item.attributes('label') === 'English name')!.get('input')
    await name().setValue('Unsaved draft')
    const retried = deferred<{ items: ReturnType<typeof summary>[] }>()
    api.get.mockReturnValueOnce(retried.promise)
    await wrapper.findAll('button').find(button => button.text() === 'Retry loading credentials')!.trigger('click')
    expect(wrapper.find('[role="alert"]').exists()).toBe(false)
    expect(wrapper.text()).toContain('Loading credentials')
    expect(wrapper.text()).not.toContain('No credentials have been saved yet.')
    expect(name().element.value).toBe('Unsaved draft')
    retried.resolve({ items: [] })
    await flushPromises()
    expect(wrapper.text()).toContain('No credentials have been saved yet.')
    expect(name().element.value).toBe('Unsaved draft')
    wrapper.unmount()
  })

  it('renders failed deletion feedback outside an open editor and recovers on retry', async () => {
    api.get.mockResolvedValue({ items: [summary('Existing credential')] })
    api.delete.mockRejectedValueOnce(new Error('conflict')).mockResolvedValueOnce(undefined)
    const wrapper = mount(AgencyConfig, { props })
    await flushPromises()
    await wrapper.get('[aria-label="Remove"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="status"]').text()).toBe('Credential action failed.')
    expect(wrapper.findAll('label').some(field => field.attributes('label') === 'Private key')).toBe(false)
    await wrapper.get('[aria-label="Remove"]').trigger('click')
    await flushPromises()
    expect(wrapper.get('[role="status"]').text()).toBe('Credential deleted.')
    wrapper.unmount()
  })

})
